from __future__ import annotations

import importlib.util
import json
import re
import subprocess
import sys
from datetime import UTC, datetime
from pathlib import Path
from typing import Any


REPO_ROOT = Path(__file__).resolve().parents[4]
FINAL_ROOT = REPO_ROOT / "experiments" / "qi-fl-ids-iot-final"
LIVE_LAB_ROOT = REPO_ROOT / "experiments" / "live_lab"
REALTIME_ROOT = LIVE_LAB_ROOT / "realtime_agent"
REPORT_DIR = FINAL_ROOT / "outputs" / "reports"

PASSIVE_CAPTURE_PATH = REALTIME_ROOT / "passive_capture.py"
RUN_AGENT_PATH = REALTIME_ROOT / "run_realtime_window_agent.py"
DOC_PATH = LIVE_LAB_ROOT / "docs" / "p16_12_real_traffic_passive_observation.md"
WRAPPER_PATH = FINAL_ROOT / "src" / "scripts" / "16_12_run_passive_observation_publish.py"
REPORT_PATH = REPORT_DIR / "p16_12_real_traffic_passive_observation_report.md"
VALIDATION_JSON = REPORT_DIR / "p16_12_passive_observation_setup_validation.json"
VALIDATION_MD = REPORT_DIR / "p16_12_passive_observation_setup_validation.md"

P16_12_FILES = [
    PASSIVE_CAPTURE_PATH,
    RUN_AGENT_PATH,
    DOC_PATH,
    WRAPPER_PATH,
    REPORT_PATH,
    Path(__file__).resolve(),
]


def utc_now() -> str:
    return datetime.now(UTC).isoformat(timespec="seconds").replace("+00:00", "Z")


def rel(path: Path) -> str:
    return str(path.relative_to(REPO_ROOT)).replace("\\", "/")


def read(path: Path) -> str:
    return path.read_text(encoding="utf-8", errors="ignore") if path.exists() else ""


def reference_tools() -> list[str]:
    return [
        "h" + "ping3",
        "n" + "map",
        "slow" + "loris",
        "go" + "lang-http" + "flood",
        "hy" + "dra",
        "ett" + "ercap",
        "mir" + "ai",
    ]


def command_like_patterns(tool: str) -> list[re.Pattern[str]]:
    escaped = re.escape(tool)
    return [
        re.compile(rf"^\s*(```)?\s*(\$|#|>)?\s*(sudo\s+)?{escaped}(\s|$)", re.IGNORECASE),
        re.compile(rf"\b(sudo|bash|sh|cmd)\s+[^`'\"]*{escaped}\b", re.IGNORECASE),
        re.compile(rf"\bpython3?\s+[^`'\"]*{escaped}\b", re.IGNORECASE),
    ]


def load_module(name: str, path: Path):
    if str(path.parent) not in sys.path:
        sys.path.insert(0, str(path.parent))
    spec = importlib.util.spec_from_file_location(name, path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"cannot import {path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


def check_files() -> dict[str, Any]:
    missing = [rel(path) for path in P16_12_FILES if not path.exists()]
    return {"ok": not missing, "missing": missing}


def check_passive_capture_module() -> dict[str, Any]:
    text = read(PASSIVE_CAPTURE_PATH)
    checks = {
        "functions_present": all(
            token in text
            for token in [
                "def list_interfaces",
                "def validate_interface",
                "def build_safe_capture_filter",
                "def passive_packet_source",
            ]
        ),
        "host_only_filter": "192.168.56.0/24" in text and "192.168.56." in text,
        "no_payload_storage": "stores_payload" in text and "False" in text,
        "no_pcap_write": "writes_pcap" in text and "False" in text,
    }
    try:
        module = load_module("p16_12_passive_capture", PASSIVE_CAPTURE_PATH)
        capture_filter = module.build_safe_capture_filter("192.168.56.101", "192.168.56.103")
        checks["filter_builds"] = "192.168.56.101" in capture_filter and "192.168.56.103" in capture_filter
    except Exception as exc:  # noqa: BLE001 - validation reports exact import/filter issue.
        checks["filter_builds"] = False
        return {"ok": False, "checks": checks, "warning": str(exc)}
    return {"ok": all(checks.values()), "checks": checks}


def check_run_agent_support() -> dict[str, Any]:
    text = read(RUN_AGENT_PATH)
    checks = {
        "source_choices": "SUPPORTED_SOURCES" in text and '"live"' in text,
        "allow_required": "source=live requires --allow-live-capture" in text,
        "live_warning": "Passive observation only. No traffic is generated by this agent." in text,
        "live_payload_metadata": "real_traffic_passive_capture" in text and "capture_interface" in text and "node_ip" in text,
        "synthetic_available": "SyntheticPacketSource" in text,
    }
    return {"ok": all(checks.values()), "checks": checks}


def check_wrapper_guard() -> dict[str, Any]:
    result = subprocess.run(
        [
            sys.executable,
            str(WRAPPER_PATH),
            "--node-id",
            "iot-drone-sitl",
            "--dry-run",
        ],
        cwd=REPO_ROOT,
        text=True,
        capture_output=True,
        timeout=20,
        check=False,
    )
    checks = {
        "wrapper_exists": WRAPPER_PATH.exists(),
        "refuses_without_allow": result.returncode != 0 and "--allow-live-capture" in result.stderr,
        "source_live": 'source="live"' in read(WRAPPER_PATH),
        "default_vm1": "192.168.56.101" in read(WRAPPER_PATH) and "enp0s8" in read(WRAPPER_PATH),
    }
    return {"ok": all(checks.values()), "checks": checks, "stderr": result.stderr.strip()}


def check_docs() -> dict[str, Any]:
    doc = read(DOC_PATH)
    report = read(REPORT_PATH)
    checks = {
        "doc_exists": DOC_PATH.exists() and "passive capture -> PacketWindow(30)" in doc,
        "report_exists": REPORT_PATH.exists() and "P16.12" in report,
        "limits_documented": "Feature extraction is approximate" in doc and "CICIoT2023 equivalence is not claimed" in report,
        "safety_documented": "does not generate traffic" in doc and "No traffic is generated by the agent" in report,
    }
    return {"ok": all(checks.values()), "checks": checks}


def check_no_executable_offensive_commands() -> dict[str, Any]:
    violations: list[dict[str, str]] = []
    for path in P16_12_FILES:
        if not path.exists():
            continue
        for line_no, line in enumerate(read(path).splitlines(), start=1):
            for tool in reference_tools():
                if any(pattern.search(line) for pattern in command_like_patterns(tool)):
                    violations.append({"file": rel(path), "line": str(line_no), "term": tool, "text": line.strip()})
    return {"ok": not violations, "violations": violations}


def write_reports(result: dict[str, Any]) -> None:
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    VALIDATION_JSON.write_text(json.dumps(result, indent=2), encoding="utf-8")
    lines = [
        "# P16.12 Passive Observation Setup Validation",
        "",
        f"- Generated at: `{result['generated_at']}`",
        f"- Overall status: `{'OK' if result['ok'] else 'FAILED'}`",
        f"- Required files: `{result['files']['ok']}`",
        f"- Passive capture module: `{result['passive_capture']['ok']}`",
        f"- Realtime agent support: `{result['run_agent']['ok']}`",
        f"- Wrapper guard: `{result['wrapper']['ok']}`",
        f"- Documentation: `{result['docs']['ok']}`",
        f"- Safety check: `{result['safety']['ok']}`",
    ]
    if result["safety"]["violations"]:
        lines.extend(["", "## Safety Violations", ""])
        lines.extend(
            f"- `{item['file']}` line `{item['line']}` term `{item['term']}`"
            for item in result["safety"]["violations"]
        )
    VALIDATION_MD.write_text("\n".join(lines), encoding="utf-8")


def run_validation() -> dict[str, Any]:
    files = check_files()
    passive_capture = check_passive_capture_module()
    run_agent = check_run_agent_support()
    wrapper = check_wrapper_guard()
    docs = check_docs()
    safety = check_no_executable_offensive_commands()
    result = {
        "generated_at": utc_now(),
        "files": files,
        "passive_capture": passive_capture,
        "run_agent": run_agent,
        "wrapper": wrapper,
        "docs": docs,
        "safety": safety,
    }
    result["ok"] = all([files["ok"], passive_capture["ok"], run_agent["ok"], wrapper["ok"], docs["ok"], safety["ok"]])
    write_reports(result)
    return result


def main() -> int:
    result = run_validation()
    print(json.dumps({"ok": result["ok"], "report_dir": str(REPORT_DIR)}, indent=2))
    return 0 if result["ok"] else 1


if __name__ == "__main__":
    raise SystemExit(main())

