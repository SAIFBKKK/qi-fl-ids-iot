#!/bin/bash
# P16.17 - Continuous Smartwatch Traffic Observer
# Lancer une seule fois avant la soutenance.
# Observation passive seulement: ce script ne genere aucun trafic reseau.

set -e

REPO_ROOT="$(cd "$(dirname "$0")/../../../../" && pwd)"
AGENT="$REPO_ROOT/experiments/live_lab/nodes/iot_smart_watch_medium/smartwatch_passive_agent.py"
LOG_FILE="$REPO_ROOT/experiments/qi-fl-ids-iot-final/outputs/reports/p1617_smartwatch_continuous_observer.jsonl"
MQTT_BROKER="192.168.56.1"

mkdir -p "$(dirname "$LOG_FILE")"

echo "[P16.17] Starting continuous smartwatch observer..."
echo "[P16.17] Passive observation only; no traffic is generated by this agent."
echo "[P16.17] Log: $LOG_FILE"
echo "[P16.17] MQTT broker: $MQTT_BROKER"
echo "[P16.17] Press Ctrl+C to stop."
echo ""

python3 "$AGENT" \
  --scenario passive \
  --interface enp0s8 \
  --node-ip 192.168.56.102 \
  --peer-ip 192.168.56.103 \
  --window-size 30 \
  --window-stride 15 \
  --input-mode original_28_scaled \
  --mqtt-broker "$MQTT_BROKER" \
  --continuous \
  --status-interval 5 \
  --log-file "$LOG_FILE" \
  --allow-live-capture \
  --log-level INFO
